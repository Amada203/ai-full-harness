import { mkdtempSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const parent = mkdtempSync(join(tmpdir(), 'architecture-gate-'));
const project = join(parent, 'pilot');
const generate = spawnSync(join(root, 'bin/new-full-project'), ['--no-git', 'pilot', parent]);
assert.equal(generate.status, 0, generate.stderr?.toString());
const run = mode => spawnSync(process.execPath, [join(project, 'scripts/architecture.mjs'), mode], { encoding: 'utf8' });
assert.notEqual(run('check').status, 0, 'fresh project cannot pass design');
copyFileSync(join(root, 'tests/fixtures/architecture.archify.json'), join(project, 'docs/architecture/ARCHITECTURE.archify.json'));
const tech = join(project, 'docs/technical/TECHNICAL_PRD.md');
writeFileSync(tech, '[Architecture](../architecture/ARCHITECTURE.html)\nARCH:author submits requirements\nARCH:renderer delivers HTML\nARCH:reviewer examines evidence\n');
let result = run('build');
assert.equal(result.status, 0, result.stderr);
assert.equal(run('check').status, 0);
const json = join(project, 'docs/architecture/ARCHITECTURE.archify.json');
const originalJson = readFileSync(json);
writeFileSync(json, Buffer.concat([originalJson, Buffer.from('\n')]));
assert.notEqual(run('check').status, 0, 'source byte changes invalidate receipt');
writeFileSync(json, originalJson);
const lockPath = join(project, '.ai/ARCHIFY_LOCK.json');
const originalLock = readFileSync(lockPath);
const badLock = JSON.parse(originalLock);
badLock.treeSha256 = '0'.repeat(64);
writeFileSync(lockPath, JSON.stringify(badLock));
assert.notEqual(run('check').status, 0, 'different tool identity must fail');
writeFileSync(lockPath, originalLock);
const missingTool = spawnSync(process.execPath, [join(project, 'scripts/architecture.mjs'), 'check'], {
  env: { ...process.env, ARCHIFY_HOME: join(parent, 'missing-tool') }, encoding: 'utf8',
});
assert.notEqual(missingTool.status, 0, 'explicit missing tool must not fall back');
const html = join(project, 'docs/architecture/ARCHITECTURE.html');
const before = readFileSync(html);
writeFileSync(html, Buffer.concat([before, Buffer.from('tampered')]));
assert.notEqual(run('check').status, 0, 'tampered HTML must fail');
writeFileSync(html, before);
writeFileSync(tech, '[Architecture](../architecture/ARCHITECTURE.html)');
assert.notEqual(run('check').status, 0, 'missing node responsibilities must fail');
const fingerprinter = readFileSync(join(project, 'scripts/lifecycle-fingerprint.sh'), 'utf8');
assert.match(fingerprinter, /emit_tree "docs\/architecture"/);
const gate = readFileSync(join(project, 'scripts/check-lifecycle-gate.sh'), 'utf8');
assert.match(gate, /architecture\.mjs" check/);
console.log(`architecture tests passed; evidence: ${project}`);
